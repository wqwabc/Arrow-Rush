# -*- coding: utf-8 -*-
"""关卡数据。

用 ASCII 图描述棋盘，改关卡时最直观：

    .   空格子        ^   向上箭头
    v   向下箭头      <   向左箭头      >   向右箭头

每一行就是棋盘的同一行，写在最上面的一行就是棋盘最上面的一行。
缩进会被 textwrap.dedent 去掉，所以可以放心写得整齐。

**每一行的字符数必须一致**：数错一位整个布局就整体偏一列。

## 布局约束（改关卡时请一并遵守）

1. **任何两个箭头都不能上下左右相邻**，必须隔开至少一格。箭头挤在一起会糊成
   一团，也看不清谁挡住了谁。等价说法：同一行里相邻两格不能都有箭头，同列同理。
2. **同一行 / 同一列里，同向箭头最多 2 个**。整行整列朝一个方向会显得很单调，
   而且一眼看不出该先动哪个；方向混着来才有"要先拆哪一头"的思考空间。
3. **不能出现循环依赖**。只要箭头 A 前进路上第一个撞到的是 B，就记为
   "A 依赖 B"（B 必须先消掉）。这条依赖关系里不能有环，有环就表示这几个箭头
   互相锁死，整关无解。最容易踩的是二元环：同一列里上方朝下 + 下方朝上，
   或同一行里左边朝右 + 右边朝左。三元、四元环更隐蔽，例如
   (0,4)← 被 (0,2)↓ 挡、(0,2)↓ 被 (2,2)→ 挡、(2,2)→ 被 (2,4)↑ 挡、
   (2,4)↑ 又被 (0,4)← 挡——四个箭头谁也出不去。
   **改完关卡一定要跑一遍求解器**，光靠肉眼很难发现长环。
4. **开局可动的箭头不能太少也不能太多**，控制在 3 个到总数三分之一之间。
   只剩一个能点会变成"唯一顺序"，玩家不用思考也能过，反而没难度。

## 判定阻挡关系时的一个坑

必须按"当前棋盘"逐格往前找第一个阻挡者。写成"先在满棋盘上找到第一个阻挡者、
再看它是否还在盘上"是错的——万一那个已经被消掉了，后面的第二个阻挡者就被漏掉了，
会误判成可以飞出。这个错误会让求解器给出根本走不通的通关顺序。

下面 12 个布局是用随机搜索在满足上述约束的前提下挑出来的，
全部用穷举求解器验证过可解，并逐关检查过 1~3 条规则。

难度分 = 箭头数 × 3 + 最长依赖链 × 2 + 被挡住的箭头数，逐关递增。
"""

from __future__ import annotations

import textwrap
from dataclasses import dataclass

CHAR_TO_DIR = {
    "^": "up",
    "v": "down",
    "<": "left",
    ">": "right",
}

DIR_TO_CHAR = {value: key for key, value in CHAR_TO_DIR.items()}

# 三个难度档，关卡按这个顺序排列
TIERS = ("入门", "进阶", "挑战")


@dataclass(frozen=True)
class Level:
    """一个关卡：名称、难度档、棋盘尺寸、允许的失误次数、初始箭头布局。"""

    name: str
    tier: str
    rows: int
    cols: int
    max_mistakes: int
    arrows: tuple  # ((row, col, direction), ...)


def _level(name: str, tier: str, max_mistakes: int, art: str) -> Level:
    lines = [line.rstrip() for line in textwrap.dedent(art).strip("\n").split("\n")]
    rows = len(lines)
    cols = max(len(line) for line in lines)
    arrows = []
    for row, line in enumerate(lines):
        for col, char in enumerate(line):
            direction = CHAR_TO_DIR.get(char)
            if direction is not None:
                arrows.append((row, col, direction))
    return Level(name=name, tier=tier, rows=rows, cols=cols,
                 max_mistakes=max_mistakes, arrows=tuple(arrows))


